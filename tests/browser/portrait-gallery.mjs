import { createRequire } from 'node:module';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const { chromium } = createRequire(import.meta.url)('playwright');
const out = process.env.AUDIT_OUT || '.artifacts/portrait-gallery';
await fs.mkdir(out,{recursive:true});
const browser = await chromium.launch();
const page = await browser.newPage({viewport:{width:1800,height:1800}});
await page.goto(process.env.AUDIT_URL || 'http://127.0.0.1:5174/pokemon-unite-draft/');
await page.locator('.setup-start').click();
await page.locator('.first-prompt-options button').first().click();
await page.waitForTimeout(400);
const seen = new Set();
let n=0;
do {
  await page.locator('.pokemon-card img').evaluateAll(imgs=>Promise.all(imgs.map(img=>img.decode())));
  for(const name of await page.locator('.pokemon-card img').evaluateAll(imgs=>imgs.map(img=>img.alt))) seen.add(name);
  await page.locator('.selection-panel').screenshot({path:`${out}/all-${++n}.png`});
  const next=page.getByRole('button',{name:'次のページ',exact:true});
  if(await next.isDisabled())break;
  await next.click();
}while(n<20);
assert.equal(seen.size,102);
await page.setViewportSize({width:503,height:727});
await page.getByRole('searchbox').fill('レシラム');
await page.locator('.pokemon-card').click();
await page.screenshot({path:`${out}/reshiram-phone.png`});
assert(await page.locator('.pokemon-card img').isVisible());
console.log('All 102 portraits rendered; Reshiram phone selection captured');
await browser.close();
